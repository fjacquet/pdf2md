//go:build ignore

// gen_std14 writes std14.go: the advance widths of the 14 standard PDF fonts,
// read from Adobe's Core14 AFM files as shipped in pdfcpu v0.16.1.
//
// Run from internal/pdf: go generate (see the directive in font.go).
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const module = "github.com/pdfcpu/pdfcpu@v0.16.1"

func main() {
	out, err := exec.Command("go", "mod", "download", "-json", module).Output()
	if err != nil {
		log.Fatalf("go mod download %s: %v", module, err)
	}
	var mod struct{ Dir string }
	if err := json.Unmarshal(out, &mod); err != nil {
		log.Fatal(err)
	}
	files, err := filepath.Glob(filepath.Join(mod.Dir, "internal/corefont/Core14_AFMs/*.afm"))
	if err != nil || len(files) != 14 {
		log.Fatalf("want 14 AFM files, got %d (%v)", len(files), err)
	}
	sort.Strings(files)

	var b bytes.Buffer
	b.WriteString(`// Code generated by gen_std14/main.go; DO NOT EDIT.

// Widths of the 14 standard fonts, derived from Adobe's Core14 AFM files
// (` + module + `/internal/corefont/Core14_AFMs). Adobe's terms allow
// use, copying and distribution for any purpose provided all copyright
// notices are retained; each font below keeps its AFM copyright line.
// Modification: only the C, WX and N fields of each CharMetrics line are kept.

package pdf

var std14Fonts = map[string]std14Metrics{
`)
	for _, path := range files {
		name, copyright, byName, byCode := parseAFM(path)
		fmt.Fprintf(&b, "// %s\n%q: {\nbyName: map[string]int{", copyright, name)
		names := make([]string, 0, len(byName))
		for n := range byName {
			names = append(names, n)
		}
		sort.Strings(names)
		for _, n := range names {
			fmt.Fprintf(&b, "%q: %d, ", n, byName[n])
		}
		b.WriteString("},\nbyCode: map[int]int{")
		codes := make([]int, 0, len(byCode))
		for c := range byCode {
			codes = append(codes, c)
		}
		sort.Ints(codes)
		for _, c := range codes {
			fmt.Fprintf(&b, "%d: %d, ", c, byCode[c])
		}
		b.WriteString("},\n},\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("std14.go", src, 0o600); err != nil {
		log.Fatal(err)
	}
}

// parseAFM reads "C <code> ; WX <width> ; N <name> ; ..." lines. Code -1 is
// a glyph outside the font's built-in encoding.
func parseAFM(path string) (string, string, map[string]int, map[int]int) {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var font, copyright string
	byName, byCode := map[string]int{}, map[int]int{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if v, ok := strings.CutPrefix(line, "FontName "); ok {
			font = strings.TrimSpace(v)
		}
		if v, ok := strings.CutPrefix(line, "Comment Copyright "); ok && copyright == "" {
			copyright = "Copyright " + strings.TrimSpace(v)
		}
		if !strings.HasPrefix(line, "C ") {
			continue
		}
		code, width, name := -1, -1, ""
		for field := range strings.SplitSeq(line, ";") {
			kv := strings.Fields(field)
			if len(kv) < 2 {
				continue
			}
			switch kv[0] {
			case "C":
				code, _ = strconv.Atoi(kv[1])
			case "WX":
				width, _ = strconv.Atoi(kv[1])
			case "N":
				name = kv[1]
			}
		}
		if width < 0 || name == "" {
			continue
		}
		byName[name] = width
		if code >= 0 {
			byCode[code] = width
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	return font, copyright, byName, byCode
}
